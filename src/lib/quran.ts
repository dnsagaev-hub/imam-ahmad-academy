  r.base ? `${r.base}${String(n).padStart(3, '0')}.mp3` : (r.files[n] ?? null)

/** Перевод аята: основной текст — жирным, пояснения в [квадратных] и (круглых) скобках — обычным. */
export function splitTranslation(text: string): { text: string; note: boolean }[] {
  return text
    .split(/(\[[^\]]*\]|\([^)]*\))/)
    .filter(Boolean)
    .map((t) => ({ text: t, note: /^[[(]/.test(t) }))
}

/** Строка для поиска: без огласовок, «аль-», апострофов и регистра. */
export function searchKey(s: string) {
  return s
    .toLowerCase()
    .replace(/[ً-ٰٟۖ-ۭ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/(^|\s)(аль|ал|ан|ар|ас|аш|ат|аз|ад|ль)[-\s]/g, '$1')
    .replace(/[‘’'ʼ`«»-]/g, '')
    .replace(/ё/g, 'е')
}

export function plural(n: number, forms: [string, string, string]): string {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return forms[2]
  if (b > 1 && b < 5) return forms[1]
  if (b === 1) return forms[0]
  return forms[2]
}

